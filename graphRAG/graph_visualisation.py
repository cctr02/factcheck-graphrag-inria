import networkx as nx
from pyvis.network import Network
import os
import sys
import webbrowser
import pickle

sys.path.append(os.path.join(os.path.dirname(__file__), ".."))

from utils.logger import setup_logger

logger = setup_logger("graphRAG/graph_visualisation.log", log_level="INFO")

def visualize_graph(graph_path, output_path="graph_visualization.html"):
    """
    Visualize a NetworkX graph saved in .gpickle format
    
    Args:
        graph_path: Path to the .gpickle file
        output_path: Path for the output HTML file
    """
    # Load the graph
    with open(graph_path, 'rb') as f:
        G = pickle.load(f)
    logger.info(f"Graph loaded: {G.number_of_nodes()} nodes, {G.number_of_edges()} edges")
    
    # Create pyvis network
    net = Network(notebook=False, height="750px", width="100%", bgcolor="#ffffff")
    
    # Graph physics configuration
    net.force_atlas_2based()
    net.show_buttons(filter_=['physics'])
    
    # Add nodes and edges
    for node in G.nodes():
        # Extract ID without "doc::" prefix
        label = node.replace("doc::", "")
        net.add_node(node, label=label, title=label)
    
    for edge in G.edges(data=True):
        net.add_edge(
            edge[0], 
            edge[1],
            value=edge[2]['weight']*10,  # Edge thickness proportional to weight
            title=f"Similarity: {edge[2]['weight']:.2f}"
        )
    
    # Save to HTML
    net.save_graph(output_path)
    logger.info(f"\nVisualization saved in: {output_path}")
    
    # Open in browser
    webbrowser.open(output_path)

if __name__ == "__main__":
    # Path to .gpickle file generated by sementicGR.py
    graph_path = "doc_graph_embed.gpickle"
    
    # Check if file exists
    if not os.path.exists(graph_path):
        logger.info(f"Error: File {graph_path} does not exist.")
        logger.info("Run sementicGR.py first to generate the graph.")
        exit(1)
        
    visualize_graph(graph_path)